// A tooltip with no translation of its own reads its short label instead of falling back to English.
const TITLE_FALLBACK: Partial<Record<UIKey, UIKey>> = {
  copyAllTitle: "copyAll", copySummaryTitle: "copy", copyTableTitle: "copyTable", playTitle: "play", pauseTitle: "pause",
};

export const UI_STRINGS: Record<LanguageCode, Strings> = { en, hinglish, hi, mr, bn, ta, te, gu, pa, kn, ml };

export function lookup(language: string, key: UIKey): string {
  const table = UI_STRINGS[language as LanguageCode];
  if (table && language !== "en") {
    if (table[key]) return table[key]!;
    const short = TITLE_FALLBACK[key];
    if (short && table[short]) return table[short]!;
  }
  return en[key];
}

